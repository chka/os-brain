package overview

import (
	"fmt"
	"io"
	"strings"

	"github.com/chka/os-brain/internal/fsguard"
	"github.com/chka/os-brain/internal/store"
	"github.com/chka/os-brain/internal/timefmt"
)

// SnapshotMarker identifies a file this command generated. Anything without it is
// somebody's own notes, and overwriting those is data loss rather than a rewrite.
//
// The exact string must not change: ns-brain writes and recognises the same one, and a
// marker that differs by a single character means neither can regenerate the other's
// snapshot, each refusing the other's file as somebody's hand-written notes.
const SnapshotMarker = "GENERATED BY `os-brain snapshot`"

// LegacySnapshotMarker is what snapshots carried before the command was renamed. Old
// snapshots still have it, and the marker is the only thing standing between `snapshot
// --out` and overwriting a file somebody hand-wrote, so it keeps being recognised.
const LegacySnapshotMarker = "GENERATED BY `brain snapshot`"

type SnapshotArgs struct {
	Out          string
	PerScope     int
	Force        bool
	AllowOutside bool
	AllowTracked bool
	JSON         bool
}

// Snapshot is a generated markdown mirror of the brain. If a project wants an auto-loaded
// memory file it must be this, never a hand-written one: two hand-maintained stores drift
// silently and the reader cannot tell which is current.
func (s *Store) Snapshot(w io.Writer, a SnapshotArgs) error {
	if a.PerScope <= 0 {
		a.PerScope = 12
	}
	doc, err := s.snapshotDoc(a.PerScope)
	if err != nil {
		return err
	}
	text := RenderSnapshot(doc)
	if a.Out == "" {
		return store.Out(w, a.JSON, text, map[string]interface{}{"markdown": text})
	}
	if err := (&fsguard.Dump{Path: a.Out, Root: s.Env.ProjectRoot(), Marker: SnapshotMarker,
		Also: []string{LegacySnapshotMarker}, Force: a.Force, AllowOutside: a.AllowOutside,
		AllowTracked: a.AllowTracked}).Write(text); err != nil {
		return err
	}
	return store.Out(w, a.JSON, fmt.Sprintf("wrote %s (mode 600, %d bytes of cleartext memory)",
		a.Out, len(text)), map[string]interface{}{"out": a.Out, "bytes": len(text)})
}

// snapshotDoc gathers the live memories a snapshot shows: guardrails, then pinned memories
// that are not guardrails, then up to perScope of the rest per scope, most important first.
func (s *Store) snapshotDoc(perScope int) (SnapshotDoc, error) {
	doc := SnapshotDoc{Project: s.Env.Project, Generated: timefmt.Now()}
	pw, pp := s.ProjectFilter("m", false)
	pins, err := s.QueryMemories("SELECT "+store.MemoryCols+", 0.0 AS bm FROM memories m WHERE "+
		pw+" AND pinned=1 AND superseded_by IS NULL ORDER BY importance DESC", pp...)
	if err != nil {
		return doc, err
	}
	guards, err := s.QueryMemories("SELECT "+store.MemoryCols+", 0.0 AS bm FROM memories m WHERE "+
		pw+" AND mem_type IN ("+store.Placeholders(len(store.GuardrailTypes))+") AND superseded_by IS NULL "+
		"ORDER BY importance DESC", append(append([]interface{}{}, pp...),
		store.ToIfaces(store.GuardrailTypes)...)...)
	if err != nil {
		return doc, err
	}

	doc.Guardrails = SnapshotRowsOf(guards)
	inGuards := map[int64]bool{}
	for _, g := range guards {
		inGuards[g.ID] = true
	}
	var onlyPinned []*store.Memory
	for _, p := range pins {
		if !inGuards[p.ID] {
			onlyPinned = append(onlyPinned, p)
		}
	}
	doc.Pinned = SnapshotRowsOf(onlyPinned)

	names, err := s.liveScopes(strings.Replace(pw, "m.", "", 1), pp)
	if err != nil {
		return doc, err
	}
	for _, sc := range names {
		args := append([]interface{}{}, pp...)
		args = append(args, sc)
		args = append(args, store.ToIfaces(store.GuardrailTypes)...)
		args = append(args, perScope)
		rs, err := s.QueryMemories("SELECT "+store.MemoryCols+", 0.0 AS bm FROM memories m WHERE "+
			pw+" AND scope=? AND superseded_by IS NULL AND pinned=0 AND mem_type NOT IN ("+
			store.Placeholders(len(store.GuardrailTypes))+") ORDER BY importance DESC, updated_at DESC, id DESC "+
			"LIMIT ?", args...)
		if err != nil {
			return doc, err
		}
		doc.Scopes = append(doc.Scopes, SnapshotScope{Name: sc, Rows: SnapshotRowsOf(rs)})
	}
	return doc, nil
}

// liveScopes is every scope holding a live memory of this project, in name order.
func (s *Store) liveScopes(projectWhere string, params []interface{}) ([]string, error) {
	rows, err := s.DB.Query("SELECT DISTINCT scope FROM memories WHERE "+
		projectWhere+" AND superseded_by IS NULL ORDER BY scope", params...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var names []string
	for rows.Next() {
		var sc string
		if err := rows.Scan(&sc); err != nil {
			return nil, err
		}
		names = append(names, sc)
	}
	return names, nil
}
